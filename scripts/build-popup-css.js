#!/usr/bin/env node
/* Builds assets/landing/popups.css from landing.css + tcf-v3-site.css.

   The V1 landing page is styled by assets/site/application.css (the product
   team's stylesheet). The registration, log-in and give windows still come
   from the prototype's landing.js and need the prototype's own styles. Loading
   landing.css as-is would restyle the whole page (.btn, .hero, .ticker ...), so
   this script fences every rule inside
     @scope (.pop-scrim, .toast, .greeter, .msheet, .portal-shell) { ... }
   :root blocks and @keyframes stay global (they can't live inside @scope).

   Run after editing landing.css or tcf-v3-site.css:  node scripts/build-popup-css.js
   (npm run build runs it first.) */
'use strict';
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
const SOURCES = ['assets/landing/landing.css', 'assets/css/tcf-v3-site.css'];
const SCOPE = '.pop-scrim, .toast, .greeter, .msheet, .portal-shell';

/* Split CSS into top-level chunks: comments dropped, each chunk is one rule or at-rule. */
function chunks(css) {
  css = css.replace(/\/\*[\s\S]*?\*\//g, '');
  const out = [];
  let depth = 0, start = 0, quote = null;
  for (let i = 0; i < css.length; i++) {
    const c = css[i];
    if (quote) { if (c === '\\') { i++; } else if (c === quote) quote = null; continue; }
    if (c === '"' || c === "'") { quote = c; continue; }
    if (c === '{') depth++;
    else if (c === '}') { depth--; if (depth === 0) { out.push(css.slice(start, i + 1).trim()); start = i + 1; } }
    else if (c === ';' && depth === 0) { const s = css.slice(start, i + 1).trim(); if (s) out.push(s); start = i + 1; }
  }
  return out.filter(Boolean);
}

/* Inside @scope every selector gets an implied ":scope " (descendant) in front, so a rule
   written for a window itself (.pop-scrim, .toast.show ...) would never match. Prefix those
   selectors with :scope so they match the scoping root. Recurses into @media blocks. */
const ROOT_RE = /^(\.pop-scrim|\.toast|\.greeter|\.msheet|\.portal-shell)(?![\w-])/;
function splitList(sel) {
  const out = []; let depth = 0, start = 0;
  for (let i = 0; i < sel.length; i++) {
    const c = sel[i];
    if (c === '(') depth++; else if (c === ')') depth--;
    else if (c === ',' && depth === 0) { out.push(sel.slice(start, i)); start = i + 1; }
  }
  out.push(sel.slice(start));
  return out.map(s => s.trim()).filter(Boolean);
}
function rootify(rule) {
  const brace = rule.indexOf('{');
  const head = rule.slice(0, brace).trim(), body = rule.slice(brace + 1, rule.lastIndexOf('}'));
  if (head.startsWith('@')) return head + '{' + chunks(body).map(rootify).join('\n') + '}';
  const sel = splitList(head).map(s => ROOT_RE.test(s) ? ':scope' + s : s).join(',');
  return sel + '{' + body + '}';
}

const globalParts = [], scopedParts = [];
for (const rel of SOURCES) {
  const css = fs.readFileSync(path.join(ROOT, rel), 'utf8');
  for (const ch of chunks(css)) {
    const head = ch.slice(0, ch.indexOf('{') < 0 ? ch.length : ch.indexOf('{')).trim();
    if (/^:root\b/.test(head) || /^@keyframes|^@font-face|^@import|^@charset/.test(head)) globalParts.push(ch);
    else if (ch.indexOf('{') > -1) scopedParts.push(rootify(ch));
  }
}

const out = '/* GENERATED by scripts/build-popup-css.js from ' + SOURCES.join(' + ') + ' — do not edit. */\n'
  + globalParts.join('\n') + '\n'
  + '@scope (' + SCOPE + ') {\n' + scopedParts.join('\n') + '\n}\n';
fs.writeFileSync(path.join(ROOT, 'assets/landing/popups.css'), out);
console.log('popups.css: ' + globalParts.length + ' global, ' + scopedParts.length + ' scoped rules');
